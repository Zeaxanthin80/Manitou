/**
 * Bridges the repo-root config files into the web app.
 *
 *   ../design-tokens.json  ->  app/tokens.css        (Tailwind @theme)
 *   ../store-config.json   ->  lib/store-config.ts   (typed constant)
 *
 * Why a generator rather than importing the JSON directly: both files live at the
 * repo root, outside the Next.js project, and bundlers do not import cleanly
 * across a project root. This script runs in plain Node before the bundler, so
 * the path is just a path.
 *
 * Both outputs are generated and git-ignored. Edit the JSON at the repo root.
 *
 * Tailwind v4 has no tailwind.config.js -- configuration is a @theme block in
 * CSS. PROJECT_PLAN Section 4.3's intent is unchanged: the tokens remain the
 * single source, only the mechanism differs.
 */

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, "../..");
const webRoot = resolve(here, "..");

const read = (name) =>
  JSON.parse(readFileSync(resolve(repoRoot, name), "utf8"));

const tokens = read("design-tokens.json");
const store = read("store-config.json");

const BANNER = (source) =>
  `/* GENERATED by scripts/build-tokens.mjs from ${source} -- do not edit.\n` +
  `   Change the value at the repo root and re-run \`npm run tokens\`. */\n\n`;

/* ------------------------------------------------------------------ CSS -- */

const lines = [];

for (const [name, value] of Object.entries(tokens.color)) {
  lines.push(`  --color-${name}: ${value};`);
}

lines.push("");
// The actual font files are loaded by next/font in app/layout.tsx, which sets
// --font-display-family / --font-body-family. Referencing them here keeps the
// token file free of any knowledge of how fonts get loaded.
lines.push(
  `  --font-display: var(--font-display-family), ${tokens.typography.fontFamily.display.slice(1).join(", ")};`,
);
lines.push(
  `  --font-body: var(--font-body-family), ${tokens.typography.fontFamily.body.slice(1).join(", ")};`,
);
for (const [name, value] of Object.entries(tokens.typography.fontWeight)) {
  lines.push(`  --font-weight-${name}: ${value};`);
}

lines.push("");
for (const [name, { size, lineHeight }] of Object.entries(
  tokens.typography.fontSize,
)) {
  lines.push(`  --text-${name}: ${size};`);
  lines.push(`  --text-${name}--line-height: ${lineHeight};`);
}

lines.push("");
// Tailwind v4 ships a DYNAMIC spacing scale: one --spacing base, multiplied on
// demand, so p-5 and p-7 exist whether or not the design system wants them.
// Section 4.3 says every margin comes from the scale and "never an arbitrary
// number", so the base is disabled and only the eight defined steps exist.
// Consequence: p-5 is a build error rather than a silent 20px.
lines.push("  --spacing: initial;");
for (const [step, value] of Object.entries(tokens.spacing)) {
  lines.push(`  --spacing-${step}: ${value};`);
}

lines.push("");
for (const [name, value] of Object.entries(tokens.radius)) {
  lines.push(`  --radius-${name}: ${value};`);
}

lines.push("");
for (const [name, value] of Object.entries(tokens.shadow)) {
  lines.push(`  --shadow-${name}: ${value};`);
}

const css =
  BANNER("design-tokens.json") +
  `@theme {\n${lines.join("\n")}\n}\n\n` +
  `/* Focus ring. Section 4.3's quality floor requires a visible keyboard focus\n` +
  `   state on every interactive element, so it is a system value rather than\n` +
  `   something each component reinvents. */\n` +
  `:focus-visible {\n` +
  `  outline: ${tokens.focus.width} solid ${tokens.focus.color};\n` +
  `  outline-offset: ${tokens.focus.offset};\n` +
  `}\n`;

writeFileSync(resolve(webRoot, "app/tokens.css"), css);

/* ------------------------------------------------------------------- TS -- */

delete store._meta; // documentation, not configuration

const ts =
  BANNER("store-config.json") +
  `export const storeConfig = ${JSON.stringify(store, null, 2)} as const;\n\n` +
  `export type StoreConfig = typeof storeConfig;\n`;

mkdirSync(resolve(webRoot, "lib"), { recursive: true });
writeFileSync(resolve(webRoot, "lib/store-config.ts"), ts);

console.log(
  `tokens: ${Object.keys(tokens.color).length} colours, ` +
    `${Object.keys(tokens.typography.fontSize).length} type steps, ` +
    `${Object.keys(tokens.spacing).length} spacing steps -> app/tokens.css`,
);
console.log(`store:  ${store.store.name} (${store.currency.code}) -> lib/store-config.ts`);
